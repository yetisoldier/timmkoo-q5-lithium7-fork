#      module-init-before-adapter mechanism drift-proof).
#   3. probe order = blob: five-rail power (D24) → GPIO pulse/INT/100 ms
#      settle (D22/D24) → EINT pre-mask(2) → 5× reg-0xfc gate (gsl_await_chip,
