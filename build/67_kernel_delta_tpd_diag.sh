#      branch (blob site c034d4f0, no release site in the blob).
#   5. tpd_local_init = blob tpd_local_init @0xc034c344 (E2): boot-mode store,
#      tpd_button_setting, i2c_add_driver, tpd_load_status==0 ⇒
#      i2c_del_driver + -1 (D22 production semantics; the diagnostic
