#!/usr/bin/env bash
# 62_kernel_delta_board.sh — D19 (display guards) + D20 (Q5 board-value port)
#   → β-touch-lcm-board build (the M4 verdict image's kernel).
#
# Reproduction of the β-touch-lcm sequence (D1…D18 via patches/kernel/*) with the
# D19 display-path guards and the D20 board-value port applied on top, built into
# a SEPARATE object dir (build-beta-touch-lcm-board) so the pinned m1b-β/β-touch/
# β-touch-lcm artifacts stay byte-stable and reproducible from 50/60/61 alone.
# Outputs:
#   build-beta-touch-lcm-board/arch/arm/boot/zImage   — β+touch+LCM+board kernel
#   out/kernel-parity-beta-touch-lcm-board.txt        — extended δ-parity
#       (§4.2.8 + D17 + D18 + D19/D20 invariants + DCT-precedence proof)
# (55_repack_boot.sh beta-touch-lcm-board → out/boot-m1b-beta-touch-lcm-board.img)
#
# D20 mechanics (bob-m4-board-port §3.2): the DCT headers are regenerated by DrvGen
# from q5/dct/dct/codegen.dws into the O dir on every build; D20's Makefile.custom
# edit places -I$(MTK_PROJECT_PATH_ROOT)/dct/dct/inc BEFORE -I$(DRVGEN_OUT)/inc so
# the source-tree Q5-pinned headers win include precedence. This stage asserts:
#   (a) every D20-pinned constant in the source headers (a reverted value fails
#       loudly — the re-pinned D15/D16 invariant, §3.3);
#   (b) the PRECEDENCE TOOK EFFECT on the compiled objects (hal_kpd.o keymap
#       bytes, kd_camera_hw.o sub-camera pin words, sd.o/accdet.o EINT
#       immediates) — the gate that proves DrvGen did not shadow the headers
#       (§3.3-1). If it fails, the fallback mechanism is the post-archprepare
#       O-dir overwrite documented in the spec — escalate, do not improvise.
# shellcheck shell=bash

set -euo pipefail
IFS=$'\n\t'
source "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/40_kernel_env.sh"

require_tools make python3 strings patch cmp git sha256sum grep objdump awk

BUILD_BOARD="${KDIR}/build-beta-touch-lcm-board"
# pinned byte-integrity of the extracted Q5 firmware header (D17, cf. 61)
D17_FW_SHA="bae204cb4dd1f6adce804af5fad91e9b3424847bd7a09e7faadacf3effbae680"
BOARD_SRC="${KDIR}/arch/arm/mach-mt6582/a106"
BOARD_DST="${KDIR}/arch/arm/mach-mt6582/q5"
OBJDUMP="${TC}objdump"

# ---------------------------------------------------------------- provenance pins
if [ -d "${REPO_ROOT}/donors" ]; then
  log "donors/ present — asserting kernel-sources pins (drift detection)"
  while read -r want lbl; do
    case "${lbl}" in
      '#'*|'') continue ;;
    esac
    f="${REPO_ROOT}/${lbl}"
    [ -f "${f}" ] || { warn "pin target missing (donor not cloned): ${lbl} — skipping (patches are self-contained)"; continue; }
    got="$(sha_of "${f}")"
    [ "${got}" = "${want}" ] || die "donor drift: ${lbl} sha ${got} != pinned ${want}"
  done < "${KSRC_MANIFEST}"
  log "kernel-sources pins verified where donors are present"
else
  warn "donors/ absent — patches are self-contained; proving build from repo state only"
fi

# ---------------------------------------------------------------- reset reference tree
# identical policy to 50/60/61 (D19/D20 touch tracked files only — the reset undoes
# them; the D-created paths are removed explicitly as before).
log "resetting reference tree to pristine clone (HEAD $(git -C "${KERNEL_REPO_ROOT}" rev-parse --short HEAD))"
git -C "${KERNEL_REPO_ROOT}" reset --hard HEAD >/dev/null
rm -rf \
  "${KDIR}/arch/arm/mach-mt6582/q5" \
  "${KDIR}/arch/arm/configs/q5_defconfig" \
  "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/gc5004_mipi_raw" \
  "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/hi253_yuv" \
  "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/hi704_yuv" \
  "${KDIR}/drivers/misc/mediatek/lens/mt6582/dw9714af" \
  "${KDIR}/drivers/misc/mediatek/lens/mt6582/dw9719af" \
  "${KDIR}/drivers/misc/mediatek/lens/mt6582/inc/DW9719AF.h" \
  "${KDIR}/drivers/input/touchscreen/mediatek/gslX680" \
  "${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_hsd" \
  "${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_boe"
BAD="$(git -C "${KERNEL_REPO_ROOT}" status --porcelain \
  | grep -v -E '^\?\? kernel-3\.10/build-(alpha|beta|beta-touch|beta-touch-lcm|beta-touch-lcm-board)/$' || true)"
[ -z "${BAD}" ] || die "unexpected reference-tree state:
${BAD}"
log "reference tree pristine (O= alpha/beta/beta-touch/beta-touch-lcm/beta-touch-lcm-board preserved)"

# ---------------------------------------------------------------- §4.2 steps 1-2
rm -rf "${BOARD_DST}"
cp -r "${BOARD_SRC}" "${BOARD_DST}"
rm -f "${KDIR}/arch/arm/configs/q5_defconfig"
cp "${KDIR}/arch/arm/configs/a106_defconfig" "${KDIR}/arch/arm/configs/q5_defconfig"
sed -i 's/^CONFIG_ARCH_MTK_PROJECT="a106"/CONFIG_ARCH_MTK_PROJECT="q5"/' \
  "${KDIR}/arch/arm/configs/q5_defconfig"
grep -q '^CONFIG_ARCH_MTK_PROJECT="q5"' "${KDIR}/arch/arm/configs/q5_defconfig" \
  || die "project rename failed"

# ---------------------------------------------------------------- apply deltas in D-order
# identical to 61 (D1→…→D4→D17→D18) plus D19 (display guards) and D20 (board port).
PATCH_ORDER=(D1 D2 D8 D9 D10 D11 D12 D13 D14 D4 D17 D18 D19 D20)
mkdir -p \
  "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/gc5004_mipi_raw" \
  "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/hi253_yuv" \
  "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/hi704_yuv" \
  "${KDIR}/drivers/misc/mediatek/lens/mt6582/dw9714af" \
  "${KDIR}/drivers/misc/mediatek/lens/mt6582/dw9719af" \
  "${KDIR}/drivers/input/touchscreen/mediatek/gslX680" \
  "${KDIR}/arch/arm/mach-mt6582/q5/touchpanel/gsl_tp" \
  "${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_hsd" \
  "${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_boe"
for pid in "${PATCH_ORDER[@]}"; do
  log "patch: ${pid}"
  (cd "${KDIR}" && patch -p1 --no-backup-if-mismatch --quiet \
    < "${REPO_ROOT}/patches/kernel/${pid}.patch") \
    || die "patch ${pid} failed to apply"
done

log "all patches applied; asserting the modified-tracked-file set"
CHANGED="$(git -C "${KERNEL_REPO_ROOT}" diff --name-only | sed 's|^kernel-3.10/||' | LC_ALL=C sort | tr '\n' ' ')"
WANT="$(printf '%s\n' \
  drivers/input/touchscreen/Kconfig \
  drivers/input/touchscreen/mediatek/Makefile \
  drivers/misc/mediatek/Kconfig.drivers \
  drivers/misc/mediatek/Makefile.custom \
  drivers/misc/mediatek/lcm/mt65xx_lcm_list.c \
  drivers/misc/mediatek/mmc-host/mt6582/sd.c \
  drivers/misc/mediatek/video/mt6582/dsi_drv.c \
  drivers/misc/mediatek/video/mt6582/mtkfb.c \
  drivers/misc/mediatek/imgsensor/inc/kd_imgsensor.h \
  drivers/misc/mediatek/imgsensor/inc/kd_imgsensor_define.h \
  drivers/misc/mediatek/imgsensor/src/mt6582/kd_sensorlist.h \
  drivers/misc/mediatek/lens/Makefile | LC_ALL=C sort | tr '\n' ' ')"
[ "${CHANGED}" = "${WANT}" ] \
  || die "unexpected tracked-file changes: got [${CHANGED}] want [${WANT}]"

# pin every delta-applied file's mtime to the commit epoch (determinism, cf. 50/60/61)
log "pinning delta-file mtimes to commit epoch ${KBUILD_HEAD_EPOCH}"
find "${KDIR}/arch/arm/mach-mt6582/q5" "${KDIR}/arch/arm/configs/q5_defconfig" \
     "${KDIR}/drivers/input/touchscreen/mediatek/gslX680" \
     "${KDIR}/drivers/input/touchscreen/Kconfig" \
     "${KDIR}/drivers/input/touchscreen/mediatek/Makefile" \
     "${KDIR}/drivers/misc/mediatek/lcm/mt65xx_lcm_list.c" \
     "${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_hsd" \
     "${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_boe" \
     "${KDIR}/drivers/misc/mediatek/imgsensor/inc/kd_imgsensor.h" \
     "${KDIR}/drivers/misc/mediatek/imgsensor/inc/kd_imgsensor_define.h" \
     "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/kd_sensorlist.h" \
     "${KDIR}/drivers/misc/mediatek/lens/Makefile" \
     "${KDIR}/drivers/misc/mediatek/Kconfig.drivers" \
     "${KDIR}/drivers/misc/mediatek/Makefile.custom" \
     "${KDIR}/drivers/misc/mediatek/video/mt6582/dsi_drv.c" \
     "${KDIR}/drivers/misc/mediatek/video/mt6582/mtkfb.c" \
     "${KDIR}/drivers/misc/mediatek/mmc-host/mt6582/sd.c" \
     "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/gc5004_mipi_raw" \
     "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/hi253_yuv" \
     "${KDIR}/drivers/misc/mediatek/imgsensor/src/mt6582/hi704_yuv" \
     "${KDIR}/drivers/misc/mediatek/lens/mt6582/dw9714af" \
     "${KDIR}/drivers/misc/mediatek/lens/mt6582/dw9719af" \
     -type f -exec touch -d "@${KBUILD_HEAD_EPOCH}" {} + 2>/dev/null || true

# ---------------------------------------------------------------- no-diff delta assertions
cmp -s "${BOARD_DST}/power/cust_battery_meter_table.h" \
       "${BOARD_SRC}/power/cust_battery_meter_table.h" \
  || die "D5 violated: q5 cust_battery_meter_table.h is not a verbatim a106 clone"
cmp -s "${BOARD_DST}/power/cust_charging.h" "${BOARD_SRC}/power/cust_charging.h" \
  || die "D6 violated: q5 cust_charging.h is not a verbatim a106 clone"
grep -q '^CONFIG_MTK_SMART_BATTERY=y$' "${KDIR}/arch/arm/configs/q5_defconfig" \
  || die "D3 violated: SMART_BATTERY not enabled"
for sym in BQ24250 BQ24261 BQ24196 FAN5405 FAN5402 BQ24158 BQ24296 BQ27541 \
           NCP1851 NCP1854 RT9536 SWCHR BQ24160 MAX8971; do
  grep -q "^# CONFIG_MTK_${sym}_SUPPORT is not set$" "${KDIR}/arch/arm/configs/q5_defconfig" \
    || die "D2 violated: ${sym} not explicitly off in q5_defconfig"
done
if ls "${KDIR}"/drivers/misc/mediatek/power/mt6582/bct24157* >/dev/null 2>&1; then
  die "D7 violated: bct24157 sources present"
fi
log "D2/D3/D5/D6/D7 invariants asserted (patches/kernel/DELTA-NOTES.md)"

# ---------------------------------------------------------------- D15 (re-pinned) + D16 (re-pinned)
# D20 edits the DCT-side files, so the old "byte-identical to a106" invariant is
# re-pinned (bob-m4 §3.3): mtk_kpd.h stays the a106 clone; the overridden DCT
# headers are compared against their Q5-PINNED contents so a stale/reverted value
# fails the build loudly.
cmp -s "${BOARD_DST}/keypad/mtk_kpd.h" "${BOARD_SRC}/keypad/mtk_kpd.h" \
  || die "D15 violated: q5 keypad/mtk_kpd.h deviates from the a106 lineage (D20 must not touch it)"
# D20 header: cust_kpd.h — the Q5 matrix wiring (keymap lines are tab-indented)
grep -q '\[0\] = KEY_VOLUMEDOWN,' "${BOARD_DST}/dct/dct/inc/cust_kpd.h" \
  || die "D15/D20 violated: cust_kpd.h keymap does not carry the Q5-pinned [0]=VOLUMEDOWN (blob 0xc08d0e34)"
grep -q '\[1\] = KEY_VOLUMEUP,' "${BOARD_DST}/dct/dct/inc/cust_kpd.h" \
  || die "D15/D20 violated: cust_kpd.h keymap does not carry the Q5-pinned [1]=VOLUMEUP (blob 0xc08d0e34)"
! grep -q '\[2\] = KEY_VOLUMEDOWN,' "${BOARD_DST}/dct/dct/inc/cust_kpd.h" \
  || die "D15/D20 violated: cust_kpd.h still carries the a106 [2]=VOLUMEDOWN form"
grep -q 'KPD_KEY_DEBOUNCE  1024' "${BOARD_DST}/dct/dct/inc/cust_kpd.h" \
  || die "D20 violated: cust_kpd.h KPD_KEY_DEBOUNCE drifted from the blob match (1024 @c04a4990)"
grep -q '^#define MTK_PMIC_PWR_KEY    8$' "${BOARD_DST}/dct/dct/inc/cust_kpd.h" \
  || die "D20 violated: cust_kpd.h MTK_PMIC_PWR_KEY drifted (PMIC-chip-level = 8)"
# D20 header: cust_gpio_usage.h — the divergent Q5 pins
gpio_usage="${BOARD_DST}/dct/dct/inc/cust_gpio_usage.h"
grep -q '^#define GPIO_ACCDET_EINT_PIN         (GPIO4 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: GPIO_ACCDET_EINT_PIN is not the Q5-pinned GPIO4 (blob 0x80000004 @c04a355c)"
grep -q '^#define GPIO_CAMERA_CMRST1_PIN         (GPIO16 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: GPIO_CAMERA_CMRST1_PIN is not the Q5-pinned GPIO16 (blob pinSet @0xc083c170+0x20)"
grep -q '^#define GPIO_CAMERA_CMPDN1_PIN         (GPIO18 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: GPIO_CAMERA_CMPDN1_PIN is not the Q5-pinned GPIO18 (blob pinSet @0xc083c170+0x30)"
grep -q '^#define GPIO_SPEAKER_EN_PIN         (GPIO8 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: GPIO_SPEAKER_EN_PIN is not the Q5-pinned GPIO8 (blob 0x80000008 @c004e454)"
grep -q '^#define GPIO_MSDC1_EINT_PIN         (GPIO3 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: GPIO_MSDC1_EINT_PIN GPIO3 missing (blob 0x80000003 @c04f0268)"
! grep -q 'GPIO_ACCDET_EINT_PIN         (GPIO0' "${gpio_usage}" \
  || die "D20 violated: a106 GPIO_ACCDET_EINT_PIN GPIO0 form still present"
! grep -q 'GPIO_CAMERA_CMRST1_PIN         (GPIO3 ' "${gpio_usage}" \
  || die "D20 violated: a106 CMRST1 GPIO3 form still present (collides with Q5 card-detect)"
! grep -q 'GPIO_CAMERA_CMPDN1_PIN         (GPIO4 ' "${gpio_usage}" \
  || die "D20 violated: a106 CMPDN1 GPIO4 form still present (collides with Q5 ACCDET)"
! grep -q 'GPIO_SPEAKER_EN_PIN         (GPIO6 ' "${gpio_usage}" \
  || die "D20 violated: a106 SPEAKER GPIO6 form still present"
# the main-camera pins byte-verified identical in the blob (assertion re-check, §3.2-7)
grep -q '^#define GPIO_CAMERA_CMRST_PIN         (GPIO9 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: main CMRST must stay GPIO9 (blob pinSet @0xc083c170+0x00)"
grep -q '^#define GPIO_CAMERA_CMPDN_PIN         (GPIO10 | 0x80000000)$' "${gpio_usage}" \
  || die "D20 violated: main CMPDN must stay GPIO10 (blob pinSet @0xc083c170+0x10)"
# headers NOT overridden must stay the a106 clone (DrvGen keeps owning them)
for f in dct/dct/inc/cust_gpio_boot.h dct/dct/inc/cust_adc.h dct/dct/inc/cust_power.h \
         dct/dct/inc/cust_eint_md1.h dct/dct/inc/pmic_drv.h; do
  cmp -s "${BOARD_DST}/${f}" "${BOARD_SRC}/${f}" \
    || die "D20 violated: ${f} must stay on the DrvGen path byte-identical to a106"
done
# D17 invariants on cust_gpio_usage.h, re-expressed as greps (byte-parity no longer
# holds post-D20; the touch pins themselves are unchanged by D20)
grep -q '^#define GPIO_CTP_EINT_PIN         (GPIO2 | 0x80000000)$' "${gpio_usage}" \
  || die "D17 violated: CTP eint pin is not GPIO2 (blob evidence)"
grep -q '^#define GPIO_CTP_RST_PIN         (GPIO14 | 0x80000000)$' "${gpio_usage}" \
  || die "D17 violated: CTP reset pin is not GPIO14 (blob evidence)"
log "D15/D16 re-pinned to Q5-pinned contents asserted (cust_kpd.h/cust_gpio_usage.h + DrvGen-path set)"

# ---------------------------------------------------------------- D17 invariants
cmp -s "${BOARD_DST}/touchpanel/gsl_tp/tpd_custom_gsl_tp.h" \
       "${BOARD_SRC}/touchpanel/gsl_tp/tpd_custom_gsl_tp.h" 2>/dev/null \
  && die "D17 violated: the a106 board must NOT already carry gsl_tp glue (clone drifted?)"
grep -q '^CONFIG_TOUCHSCREEN_MTK_GSL_TP=y$' "${KDIR}/arch/arm/configs/q5_defconfig" \
  || die "D17 violated: GSL_TP not enabled in q5_defconfig"
# the D17 generated firmware must still be the pinned extraction
fw_sha="$(sha_of "${KDIR}/drivers/input/touchscreen/mediatek/gslX680/gslX680_fw_q5.h")"
[ "${fw_sha}" = "${D17_FW_SHA}" ] || die "D17 violated: extracted fw sha ${fw_sha} != pin ${D17_FW_SHA}"
log "D17 invariants asserted (GSL_TP on, fw bytes pinned)"

# ---------------------------------------------------------------- D18 invariants
! grep -q "gc9503v" "${BOARD_SRC}/lcm/mt65xx_lcm_list.c" 2>/dev/null \
  || die "D18 violated: the pristine a106 lcm list must not already carry gc9503v entries"
lcm_list="${KDIR}/drivers/misc/mediatek/lcm/mt65xx_lcm_list.c"
grep -q 'extern LCM_DRIVER gc9503v_wvga_dsi_vdo_hsd_drv;' "${lcm_list}" \
  || die "D18 violated: hsd extern missing from mt65xx_lcm_list.c"
grep -q 'extern LCM_DRIVER gc9503v_wvga_dsi_vdo_boe_drv;' "${lcm_list}" \
  || die "D18 violated: boe extern missing from mt65xx_lcm_list.c"
grep -q '#if defined(GC9503V_WVGA_DSI_VDO_HSD)' "${lcm_list}" \
  || die "D18 violated: hsd list entry missing from mt65xx_lcm_list.c"
grep -q '#if defined(GC9503V_WVGA_DSI_VDO_BOE)' "${lcm_list}" \
  || die "D18 violated: boe list entry missing from mt65xx_lcm_list.c"
defconfig="${KDIR}/arch/arm/configs/q5_defconfig"
grep -q '^CONFIG_CUSTOM_KERNEL_LCM="gc9503v_wvga_dsi_vdo_hsd gc9503v_wvga_dsi_vdo_boe"$' "${defconfig}" \
  || die "D18 violated: q5_defconfig LCM line is not the blob-locked gc9503v pair"
! grep -q 'hx8369b' "${defconfig}" \
  || die "D18 violated: hx8369b still referenced by q5_defconfig"
grep -q '^CONFIG_LCM_HEIGHT="800"$' "${defconfig}" \
  || die "D18 violated: CONFIG_LCM_HEIGHT must stay 800"
grep -q '^CONFIG_LCM_WIDTH="480"$' "${defconfig}" \
  || die "D18 violated: CONFIG_LCM_WIDTH must stay 480"
for d in hsd boe; do
  dir="${KDIR}/drivers/misc/mediatek/lcm/gc9503v_wvga_dsi_vdo_${d}"
  for f in "gc9503v_wvga_dsi_vdo_${d}.c" Makefile; do
    [ -s "${dir}/${f}" ] || die "D18 violated: missing ${dir}/${f}"
  done
  grep -q "\.name           = \"gc9503v_wvga_dsi_vdo_${d}\"" \
    "${dir}/gc9503v_wvga_dsi_vdo_${d}.c" \
    || die "D18 violated: ${d} driver .name is not the LK-matched blob string"
done
log "D18 invariants asserted (gc9503v pair wired, hx8369b unwired, names = LK contract, 480x800 kept)"

# ---------------------------------------------------------------- D19 invariants (source level)
mtkfb="${KDIR}/drivers/misc/mediatek/video/mt6582/mtkfb.c"
dsi_drv="${KDIR}/drivers/misc/mediatek/video/mt6582/dsi_drv.c"
grep -q 'D19: no LCM driver found after cmdline parse + autodetect' "${mtkfb}" \
  || die "D19 violated: mtkfb.c total-miss marker missing"
grep -q 'r = -ENODEV;' "${mtkfb}" \
  || die "D19 violated: mtkfb.c miss guard does not set -ENODEV"
grep -q 'extern LCM_DRIVER \*lcm_drv;' "${mtkfb}" \
  || die "D19 violated: mtkfb.c miss guard lost the lcm_drv extern"
grep -c -F -- '(D19: 100ms budget)' "${dsi_drv}" | grep -q '^4$' \
  || die "D19 violated: dsi_drv.c must bound exactly the four enumerated polls"
grep -q 'fail_exit:' "${dsi_drv}" \
  || die "D19 violated: dsi_drv.c fail_exit restore tail missing"
log "D19 invariants asserted (miss marker + 4 bounded polls + fail_exit)"

# ---------------------------------------------------------------- D20 invariants (source level)
# (1) the include-precedence line, in the right position — before $(DRVGEN_OUT)/inc
mkcustom="${KDIR}/drivers/misc/mediatek/Makefile.custom"
grep -q '^             -I\$(MTK_PROJECT_PATH_ROOT)/dct/dct/inc \\$' "${mkcustom}" \
  || die "D20 violated: Makefile.custom dct/dct/inc precedence line missing"
if [ "$(grep -n -- '-I\$(MTK_PROJECT_PATH_ROOT)/dct/dct/inc' "${mkcustom}" | head -1 | cut -d: -f1)" -gt \
     "$(grep -n -- '-I\$(DRVGEN_OUT)/inc' "${mkcustom}" | head -1 | cut -d: -f1)" ]; then
  die "D20 violated: the dct/dct/inc -I must come BEFORE the DRVGEN_OUT/inc -I (include order is what shadows DrvGen)"
fi
# (2) cust_eint.h pinned contents
eint="${BOARD_DST}/dct/dct/inc/cust_eint.h"
grep -q '^#define CUST_EINT_MSDC1_INS_NUM              3$' "${eint}" \
  || die "D20 violated: CUST_EINT_MSDC1_INS_NUM is not the Q5-pinned 3 (blob ch3)"
grep -q '^#define CUST_EINT_MSDC1_INS_DEBOUNCE_CN      0$' "${eint}" \
  || die "D20 violated: CUST_EINT_MSDC1_INS_DEBOUNCE_CN is not the Q5-pinned 0 (blob deb(3,0) @c04f02d8)"
grep -q '^#define CUST_EINT_ACCDET_NUM              4$' "${eint}" \
  || die "D20 violated: CUST_EINT_ACCDET_NUM is not the Q5-pinned 4 (blob ch4)"
! grep -q '^#define CUST_EINT_MSDC1_INS_NUM              8$' "${eint}" \
  || die "D20 violated: the a106 MSDC1 ch8 form is still present"
! grep -q '^#define CUST_EINT_ACCDET_NUM              0$' "${eint}" \
  || die "D20 violated: the a106 ACCDET ch0 form is still present"
# proven MATCH class (§3.2: blobs re-verified, must not drift)
grep -q '^#define CUST_EINT_MT6323_PMIC_NUM              25$' "${eint}" \
  || die "D20 violated: PMIC EINT must stay 25 (blob PMIC_EINT_SETTING @c0510e2c = ch25)"
grep -q '^#define CUST_EINT_MT6323_PMIC_TYPE[[:space:]]*CUST_EINTF_TRIGGER_HIGH$' "${eint}" \
  || die "D20 violated: PMIC EINT type must stay TRIGGER_HIGH (blob flag 4 @c0510e6c)"
grep -q '^#define CUST_EINT_ACCDET_DEBOUNCE_CN      256$' "${eint}" \
  || die "D20 violated: ACCDET debounce must stay 256 (blob deb(4,256) @c04a357c)"
